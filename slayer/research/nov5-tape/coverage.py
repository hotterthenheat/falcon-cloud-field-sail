"""Data-coverage table for a study day: what is there, at what resolution, what is missing.

  python3 coverage.py 20261105 -> results/COVERAGE_<D>.md (the hand-written notes live in COVERAGE.md)
"""
import glob, os, sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import load  # noqa: E402

RES = os.path.join(HERE, 'results')


def mb(path):
    if os.path.isdir(path):
        return sum(os.path.getsize(f) for f in glob.glob(os.path.join(path, '**', '*'), recursive=True) if os.path.isfile(f)) / 1e6
    return os.path.getsize(path) / 1e6 if os.path.exists(path) else 0.0


def run(D):
    d = load.ddir(D)
    L = [f'# Data coverage, {D[:4]}-{D[4:6]}-{D[6:]} (generated by coverage.py)\n',
         '| item | source | resolution | rows / contracts | span | size MB | notes |', '|---|---|---|---:|---|---:|---|']
    for sym, res in (('SPX', '1s'), ('VIX', '1s'), ('VIX1D', '1m'), ('VIX9D', '1m'), ('VIX3M', '1m')):
        f = os.path.join(d, f'idx_{sym}_{res}.parquet')
        if os.path.exists(f):
            x = pd.read_parquet(f); x = x[x.px > 0]
            L.append(f'| {sym} index | ThetaData /index/history/price | {res} | {len(x):,} | {load.clock(x.ms.min() / 1000)}-{load.clock(x.ms.max() / 1000)} | {mb(f):.1f} | |')
    f = os.path.join(d, 'spy_q1s.parquet')
    if os.path.exists(f):
        x = pd.read_parquet(f)
        L.append(f'| SPY NBBO | /stock/history/quote | 1s | {len(x):,} | {load.clock(x.ms.min() / 1000)}-{load.clock(x.ms.max() / 1000)} | {mb(f):.1f} | ES futures: not in the feed |')
    ks = sorted(float(k) for k in pd.read_csv(os.path.join(os.path.dirname(__file__), 'results', f'strikes_{D}.csv')).strike) \
        if os.path.exists(os.path.join(RES, f'strikes_{D}.csv')) else None
    c = load.chain(D)
    n_c = c.groupby(['k', 'r']).ngroups
    live = c[(c.bid > 0) | (c.ask > 0)].groupby(['k', 'r']).ngroups
    L.append(f'| SPXW 0DTE NBBO + greeks/IV | /option/history/greeks/first_order | 1m (quote in force at the stamp) | {n_c} contracts ({live} ever quoted), {len(c):,} rows | 09:30-16:00 | {mb(os.path.join(d, f"g1m_{D}_greeks.parquet")):.1f} | delta/IV are Theta\'s (calendar clock); the study re-solves IV on the trading clock |')
    o = load.ohlc(D)
    if len(o):
        L.append(f'| SPXW 0DTE volume (OHLC, count, vwap) | /option/history/ohlc | 1m | {o.groupby(["k", "r"]).ngroups} contracts, {int(o.v.sum()):,} contracts traded | 09:30-16:00 | {mb(os.path.join(d, f"g1m_{D}_ohlc.parquet")):.1f} | |')
    q = glob.glob(os.path.join(d, 'q1s', '*.npz'))
    nq = sum(1 for f in q if 's' in np.load(f).files and len(np.load(f)['s']))
    L.append(f'| SPXW 0DTE NBBO | /option/history/quote interval=1s | 1s | {nq} contracts with data (of {len(q)} files) | | {mb(os.path.join(d, "q1s")):.1f} | |')
    t = load.trades(D)
    L.append(f'| SPXW 0DTE prints | /option/history/trade_quote | tick | {"-" if t is None else f"{len(t):,} prints"} | | {mb(os.path.join(d, "trades_0dte.parquet")):.1f} | |')
    for e in sorted(f[4:12] for f in os.listdir(d) if f.startswith('g1m_') and f.endswith('_greeks.parquet') and f[4:12] != D):
        x = load.chain(D, e)
        L.append(f'| SPXW {e} NBBO + greeks (term) | greeks/first_order | 1m | {x.groupby(["k", "r"]).ngroups} contracts | | {mb(os.path.join(d, f"g1m_{e}_greeks.parquet")):.1f} | strikes within the day range +-1.5% |')
    oi = load.oi(D)
    L.append(f'| SPXW open interest, all expiries | /option/history/open_interest (morning report = prior close) | daily | {len(oi):,} rows, {oi.exp.nunique()} expiries, 0DTE {int(oi[oi.exp == int(D)].oi.sum()):,} contracts | stamped {oi.stamp.min()[:19]} | {mb(os.path.join(d, "oi_all.parquet")):.1f} | |')
    for r in ('SPXW', 'SPX'):
        f = os.path.join(d, f'eodgreeks_prior_{r}.parquet')
        if os.path.exists(f):
            x = pd.read_parquet(f)
            L.append(f'| {r} prior-session EOD greeks (IV, gamma) | /option/history/greeks/eod | daily | {len(x):,} rows, {x.exp.nunique()} expiries | | {mb(f):.1f} | the book\'s non-0DTE vols |')
    f = os.path.join(d, 'book.parquet')
    if os.path.exists(f):
        b = pd.read_parquet(f)
        L.append(f'| rebuilt gamma book (flip, net, walls) | book_nov.py (EDGE-G port) | 1m | {len(b)} reads | {load.clock(b.t.min())}-{load.clock(b.t.max())} | {mb(f):.2f} | point in time |')
    fl, nw = load.flow(D), load.news(D)
    if len(fl):
        rth = fl[(fl.s >= load.RTH0) & (fl.s < load.RTH1)]
        L.append(f'| UW flow alerts | live recorder flow-*.jsonl.gz (created_at) | as published | {len(fl):,} on the ET day, {len(rth):,} in RTH, SPXW {int((rth.ticker == "SPXW").sum())} | first {load.clock(fl.s.min())}, last {load.clock(fl.s.max())} | | recorder up from 09:21 ET (first poll back-filled the last 200) |')
    if len(nw):
        rth = nw[(nw.s >= 8 * 3600) & (nw.s < load.RTH1)]
        L.append(f'| UW headlines | live recorder news-*.jsonl.gz (created_at) | as published | {len(nw):,} unique on the ET day, {len(rth):,} 08:00-16:00 | first {load.clock(nw.s.min())} | | |')
    cr = load.compass_rows(D)
    if cr is not None:
        L.append(f'| Compass scored rows (SPXW) | slayer/.cache/compass/rows | every 5 min from 09:45 | {len(cr):,} rows, {cr.t.nunique()} marks | {load.clock(cr.t.min())}-{load.clock(cr.t.max())} | | p1 score per contract |')
    sc = f'/home/user/falcon-cloud-field-sail/v2data/live/scan/{D[:4]}-{D[4:6]}-{D[6:]}'
    if os.path.isdir(sc):
        L.append(f'| 458-name scanner snapshots | v2data/live/scan | ~1 min | {len(glob.glob(sc + "/chain-*"))} chain / {len(glob.glob(sc + "/ctx-*"))} ctx / {len(glob.glob(sc + "/under-*"))} under | | | SPXW rows in ctx (flow, vendor GEX, VIX family) |')
    L.append(f'\nTotal under v2data/nov5-tape/{D}: {mb(d):.0f} MB.\n')
    os.makedirs(RES, exist_ok=True)
    open(os.path.join(RES, f'COVERAGE_{D}.md'), 'w').write('\n'.join(L) + '\n')
    return '\n'.join(L)


if __name__ == '__main__':
    print(run(sys.argv[1]))
