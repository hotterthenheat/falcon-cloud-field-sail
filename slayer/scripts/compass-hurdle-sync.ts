/*
  The research hurdle, in one place for Compass: reads research/edge0dte/results/HURDLE.md (PROTOCOL §5, written by the
  foundation worker) and writes src/data/compassHurdle.gen.ts, the only copy any Compass code reads
  (src/data/compassHurdle.ts). When HURDLE.md changes (its final version), run this once and commit both:
    npx tsx scripts/compass-hurdle-sync.ts
  scripts/compass-cost-proof.ts fails while the generated file is behind the markdown.
*/
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const HURDLE_MD = 'research/edge0dte/results/HURDLE.md';
export const HURDLE_GEN = 'src/data/compassHurdle.gen.ts';

export interface ParsedRow {
  root: string;
  /** 30-minute bucket ('09:30' … '15:30'), or 'all' (pooled over buckets) */
  bucket: string;
  /** minutes, or 'close' */
  h: number | 'close';
  times: number;
  /** median round-trip cost of the 0.30-delta option, fraction of premium */
  cost: number | null;
  /** the sign-aligned mean Z a long 0.30-delta option needs for zero expected net P&L, with its 95% interval */
  hz: number | null;
  lo: number | null;
  hi: number | null;
}

const num = (s: string) => {
  const v = Number(s.replace('+', '').replace('%', '').trim());
  return Number.isFinite(v) ? v : null;
};

/** The rows of every root's table, and the sample (sessions per root). */
export function parseHurdle(md: string): { rows: ParsedRow[]; sessions: Record<string, number> } {
  const rows: ParsedRow[] = [];
  const sessions: Record<string, number> = {};
  let section = '';
  for (const line of md.split('\n')) {
    const head = /^##\s+(\S+)\s*$/.exec(line);
    if (head) {
      section = head[1];
      continue;
    }
    if (!line.startsWith('|')) continue;
    const cells = line.split('|').slice(1, -1).map(c => c.trim());
    if (section === 'Sample' && cells.length >= 3 && /^[A-Z]+$/.test(cells[0])) {
      const n = num(cells[2]);
      if (n != null) sessions[cells[0]] = n;
      continue;
    }
    if (!/^[A-Z]+$/.test(section) || cells.length < 7) continue;
    const bucket = cells[0];
    if (!/^(\d\d:\d\d|all)$/.test(bucket)) continue;
    const h = cells[1] === 'close' ? 'close' : num(cells[1]);
    if (h == null) continue;
    const cost = /^([\d.]+)%/.exec(cells[3]);
    const hz = /^([+-]?[\d.]+)\s*\[([+-]?[\d.]+),\s*([+-]?[\d.]+)\]/.exec(cells[6]);
    rows.push({
      root: section,
      bucket,
      h,
      times: num(cells[2]) ?? 0,
      cost: cost ? Number((Number(cost[1]) / 100).toFixed(6)) : null,
      hz: hz ? Number(hz[1]) : null,
      lo: hz ? Number(hz[2]) : null,
      hi: hz ? Number(hz[3]) : null,
    });
  }
  return { rows, sessions };
}

/** The generated module's text for a HURDLE.md. */
export function hurdleModule(md: string): string {
  const { rows, sessions } = parseHurdle(md);
  const sha = createHash('sha256').update(md).digest('hex');
  return `/* GENERATED by scripts/compass-hurdle-sync.ts from ${HURDLE_MD}: do not edit. Run the script when HURDLE.md changes. */
import type { HurdleRow } from './compassHurdle';

export const HURDLE_SHA256 = '${sha}';
/** DISCOVERY sessions behind each root's numbers (HURDLE.md "Sample") */
export const HURDLE_SESSIONS: Record<string, number> = ${JSON.stringify(sessions)};
export const HURDLE_ROWS: HurdleRow[] = [
${rows.map(r => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const md = readFileSync(join(root, HURDLE_MD), 'utf8');
  writeFileSync(join(root, HURDLE_GEN), hurdleModule(md));
  const { rows, sessions } = parseHurdle(md);
  console.log(`wrote ${HURDLE_GEN}: ${rows.length} rows, sessions ${JSON.stringify(sessions)}`);
}
